test('一个真实标题内逐字符计数，重复字符按双方可用次数，车型数字不从年份或长数字中拆',()=>{
  const title='2015款 北京现代ix25 1.6L 手动两驱时尚型GS';
  assert.deepEqual(literalScore(units('北京现代25'),title),{count:6,matched:'北京现代25'});
  assert.equal(literalScore(units('北京京现代25'),title).count,6);
  assert.equal(literalScore(units('2015'),title).count,0);
  assert.equal(literalScore(units('25'),'2025款 岚川250').count,0);
});
test('换品牌换车系：系列名和别名均不含询价片段，按具体车型实得字符取胜，不跨配置拼分',()=>{
  const store=new DataStore(':memory:');
  try{
    store.replaceBrands('passenger',[{id:'b',name:'岚川',initial:'L'}]);
    store.replaceSeries('passenger','b',[{id:'a',name:'云舟'},{id:'b',name:'原野'}]);
    const row=(id,label)=>({id,year:'2020',name:'2020款 江城岚川'+label,minRegistrationYear:'2020',maxRegistrationYear:'2026'});
    store.replaceModels('passenger','b','a',[row('101','AB28 蓝焰'),row('102','AB28 星河')]);
    store.replaceModels('passenger','b','b',[row('103','XYZ28 蓝焰星河')]);
    store.replaceRegions([{id:'20',name:'广东',cities:[{id:'20',name:'广州'}]}]);
    const result=makeParser(store.db,{today})({text:'20年江城岚川28，蓝 焰 星 河，8万公里'});
    assert.equal(result.job?.input.modelId,'103',JSON.stringify(result));
    assert.equal(result.matchPath,'catalog-title-characters');
    assert.deepEqual(result.titleMatch,{count:10,matched:'江城岚川28蓝焰星河'});
  }finally{store.db.close();}
});
